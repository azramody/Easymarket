"""Runtime configuration, read from environment variables."""
from __future__ import annotations

import json
import os
from dataclasses import dataclass, field
from pathlib import Path
from zoneinfo import ZoneInfo

REPO_ROOT = Path(__file__).resolve().parents[2]
PIPELINE_ROOT = Path(__file__).resolve().parents[1]
TOPICS_FILE = REPO_ROOT / "shared" / "topics.json"
ASSETS_DIR = PIPELINE_ROOT / "assets"

TIMEZONE = ZoneInfo(os.environ.get("EASYMARKET_TZ", "America/New_York"))

# Spoken words per minute used to size scripts.
WORDS_PER_MINUTE = 150
DAILY_MINUTES = 10
EXTENDED_MINUTES = 30

DISCLAIMER = (
    "Quick note before you go: easymarket is for information and education only. "
    "The facts in this episode come from the sources listed in your show notes, and the "
    "analysis is generated by AI, so it can be wrong or incomplete. None of this is "
    "financial, investment, tax, or legal advice."
)


@dataclass
class Settings:
    gemini_api_key: str | None = field(default_factory=lambda: os.environ.get("GEMINI_API_KEY"))
    gemini_model: str = field(default_factory=lambda: os.environ.get("GEMINI_MODEL", "gemini-2.5-flash"))
    fred_api_key: str | None = field(default_factory=lambda: os.environ.get("FRED_API_KEY"))
    gnews_api_key: str | None = field(default_factory=lambda: os.environ.get("GNEWS_API_KEY"))
    supabase_url: str | None = field(default_factory=lambda: os.environ.get("SUPABASE_URL"))
    supabase_service_key: str | None = field(default_factory=lambda: os.environ.get("SUPABASE_SERVICE_ROLE_KEY"))
    tts_engine: str = field(default_factory=lambda: os.environ.get("TTS_ENGINE", "kokoro"))
    kokoro_model: str = field(default_factory=lambda: os.environ.get("KOKORO_MODEL", str(ASSETS_DIR / "kokoro" / "kokoro-v1.0.onnx")))
    kokoro_voices: str = field(default_factory=lambda: os.environ.get("KOKORO_VOICES", str(ASSETS_DIR / "kokoro" / "voices-v1.0.bin")))
    audio_retention_days: int = field(default_factory=lambda: int(os.environ.get("AUDIO_RETENTION_DAYS", "30")))


def load_topics() -> dict:
    with open(TOPICS_FILE, encoding="utf-8") as f:
        data = json.load(f)
    return {t["id"]: t for t in data["topics"]}
